Rtpt3ExactOutput280030 ExecuteRtpt3Exact280030(
    const Rtpt3ExactInput280030& input) {
    Rtpt3ExactOutput280030 out{};
    const bool controlComplete =
        input.controlKnown &&
        input.control.geomScreenKnown &&
        input.control.geomOffsetKnown &&
        input.control.depthCueKnown &&
        input.control.geomScreen <= 0xFFFFu &&
        input.control.depthCueA >= -0x8000 &&
        input.control.depthCueA <= 0x7FFF;
    if (!input.matrixKnown || !input.verticesKnown || !controlComplete) {
        return out;
    }

    const std::array<int32_t, 9> rotation =
        DecodeRotation(input.matrix);
    const uint16_t h = static_cast<uint16_t>(input.control.geomScreen);
    const int16_t dqa = static_cast<int16_t>(input.control.depthCueA);
    uint32_t flags = 0u;

    for (std::size_t vertexIndex = 0u;
         vertexIndex < input.vertices.size();
         ++vertexIndex) {
        const VertexS16& vertex = input.vertices[vertexIndex];
        std::array<int64_t, 3> rawMac{};
        std::array<int32_t, 3> mac{};
        for (std::size_t component = 0u; component < rawMac.size();
             ++component) {
            rawMac[component] = TransformRtptComponent(
                rotation, input.matrix, vertex, component, flags);
            mac[component] = TruncateSigned32(
                ArithmeticShiftRight(rawMac[component], 12u));
        }

        const int32_t ir1 = ClampIr123(mac[0], 0u, flags);
        const int32_t ir2 = ClampIr123(mac[1], 1u, flags);
        // RTPT tests the pre-MAC32 44-bit Z result (after SAR 12) for the IR3
        // saturation flag; the separately clamped MAC3 register value is not
        // needed by this three-vertex output contract.
        const int32_t shiftedZ = TruncateSigned32(
            ArithmeticShiftRight(rawMac[2], 12u));
        ClampIr123(shiftedZ, 2u, flags);

        const uint16_t sz = ClampSz(shiftedZ, flags);
        const uint32_t quotient = DivideExactHOverSz(h, sz, flags);

        const int64_t sxMac0 =
            static_cast<int64_t>(quotient) * ir1 +
            input.control.geomOffsetX;
        const int64_t syMac0 =
            static_cast<int64_t>(quotient) * ir2 +
            input.control.geomOffsetY;
        CheckMac0Overflow(sxMac0, flags);
        CheckMac0Overflow(syMac0, flags);

        const int32_t sx = ClampScreenCoordinate(
            ArithmeticShiftRight(sxMac0, 16u),
            kFlagSxSaturated,
            flags);
        const int32_t sy = ClampScreenCoordinate(
            ArithmeticShiftRight(syMac0, 16u),
            kFlagSySaturated,
            flags);

        out.sxy[vertexIndex].known = true;
        out.sxy[vertexIndex].word = PackSxyWord(sx, sy);
        out.szAfterRtpt.elementKnown[vertexIndex + 1u] = true;
        out.szAfterRtpt.sz[vertexIndex + 1u] = sz;

        if (vertexIndex + 1u == input.vertices.size()) {
            const int64_t depthCueMac0 =
                static_cast<int64_t>(quotient) * dqa +
                input.control.depthCueB;
            CheckMac0Overflow(depthCueMac0, flags);
            out.ir0 = ClampIr0(static_cast<int32_t>(
                                   ArithmeticShiftRight(depthCueMac0, 12u)),
                               flags);
        }
    }

    if ((flags & kFlagErrorSourceMask) != 0u) {
        flags |= kFlagError;
    }
    out.known = true;
    out.flagAfterRtptKnown = true;
    out.flagAfterRtpt = flags;
    out.ir0Known = true;
    return out;
}

RtptRtps4Output8003F710 PsxCall8003F710_RotTransPers4RtptRtpsGap(
    const RtptRtps4Input8003F710& input) {
    RtptRtps4Output8003F710 out{};
    out.gap.matrixInputComplete = input.matrixKnown;
    out.gap.controlInputComplete =
        input.controlKnown &&
        input.control.geomScreenKnown &&
        input.control.geomOffsetKnown;
    out.gap.vertexInputComplete = input.verticesKnown;
    out.inputsCompleteForGeometry =
        input.matrixKnown &&
        input.verticesKnown &&
        out.gap.controlInputComplete;
    out.schedule.loadedRtptDataRegs0005 = input.verticesKnown;
    out.schedule.rtpt280030Called = input.verticesKnown;
    out.schedule.storedRtptSxy012 = input.verticesKnown;
    out.schedule.loadedRtpsDataRegs0001 = input.verticesKnown;
    out.schedule.rtps180001Called = input.verticesKnown;
    out.schedule.storedRtpsSxy2AndIr0 = input.verticesKnown;

    if (input.matrixKnown && input.verticesKnown) {
        for (std::size_t i = 0; i < out.vertexTrace.size(); ++i) {
            out.vertexTrace[i] =
                ComputeVertexTrace(input.matrix, input.vertices[i]);
        }
        out.gap.depthInputComputed = true;

        out.szAfterRtpt.elementCandidateKnown[1] = true;
        out.szAfterRtpt.elementCandidateKnown[2] = true;
        out.szAfterRtpt.elementCandidateKnown[3] = true;
        out.szAfterRtpt.candidateSz[1] = out.vertexTrace[0].szCandidate;
        out.szAfterRtpt.candidateSz[2] = out.vertexTrace[1].szCandidate;
        out.szAfterRtpt.candidateSz[3] = out.vertexTrace[2].szCandidate;

        out.szAfterRtps.elementCandidateKnown[0] = true;
        out.szAfterRtps.elementCandidateKnown[1] = true;
        out.szAfterRtps.elementCandidateKnown[2] = true;
        out.szAfterRtps.elementCandidateKnown[3] = true;
        out.szAfterRtps.candidateSz[0] = out.vertexTrace[0].szCandidate;
        out.szAfterRtps.candidateSz[1] = out.vertexTrace[1].szCandidate;
        out.szAfterRtps.candidateSz[2] = out.vertexTrace[2].szCandidate;
        out.szAfterRtps.candidateSz[3] = out.vertexTrace[3].szCandidate;
        out.szAfterRtps.candidateKnown = true;
        out.sz3AfterRtpsCandidateKnown = true;
        out.sz3AfterRtpsCandidate = out.vertexTrace[3].szCandidate;
    }

    if (input.controlKnown && input.control.geomScreenKnown) {
        for (std::size_t i = 0; i < out.division.size(); ++i) {
            GteDivisionTrace& division = out.division[i];
            division.inputsKnown = out.vertexTrace[i].depthCandidateKnown;
            division.h = input.control.geomScreen;
            if (division.inputsKnown) {
                division.sz = out.vertexTrace[i].szCandidate;
                division.quotient = DivideCandidateHOverSz(
                    division.h, division.sz);
                division.quotientCandidateKnown = true;
                division.divideOverflowCandidate =
                    division.sz == 0u || division.quotient == 0x1FFFFu;
                division.divideOverflowCandidateKnown = true;
            }
        }
        out.gap.divisionInputsComputed = out.gap.depthInputComputed;
    }

    if (input.controlKnown &&
        input.control.geomScreenKnown &&
        input.control.geomOffsetKnown) {
        for (std::size_t i = 0; i < out.projectionInput.size(); ++i) {
            GteProjectionInputTrace& projection = out.projectionInput[i];
            projection.inputsKnown =
                out.vertexTrace[i].transformCandidateKnown &&
                out.vertexTrace[i].depthCandidateKnown;
            projection.h = input.control.geomScreen;
            projection.ofx = input.control.geomOffsetX;
            projection.ofy = input.control.geomOffsetY;
            if (projection.inputsKnown) {
                projection.mac1 = out.vertexTrace[i].macCandidate[0];
                projection.mac2 = out.vertexTrace[i].macCandidate[1];
                projection.sz = out.vertexTrace[i].szCandidate;
                if (out.division[i].quotientCandidateKnown) {
                    projection.sxCandidate =
                        ProjectCandidate(projection.mac1,
                                         out.division[i].quotient,
                                         projection.ofx);
                    projection.syCandidate =
                        ProjectCandidate(projection.mac2,
                                         out.division[i].quotient,
                                         projection.ofy);
                    projection.sxyCandidateWord =
                        PackSxyWord(projection.sxCandidate,
                                    projection.syCandidate);
                    projection.sxyCandidateKnown = true;
                    out.sxy[i].candidateKnown = true;
                    out.sxy[i].candidateX = projection.sxCandidate;
                    out.sxy[i].candidateY = projection.syCandidate;
                    out.sxy[i].candidateWord = projection.sxyCandidateWord;
                }
            }
        }
    }

    if (out.vertexTrace[3].depthCandidateKnown) {
        out.sz3AfterRtpsCandidateKnown = true;
        out.sz3AfterRtpsCandidate = out.vertexTrace[3].szCandidate;
        out.returnValueCandidateKnown = true;
        out.returnValueCandidate = static_cast<uint32_t>(
            static_cast<int32_t>(out.sz3AfterRtpsCandidate) >> 2);
    }

    out.sxyWordsKnown = true;
    for (const GteSxy& sxy : out.sxy) {
        out.sxyWordsKnown = out.sxyWordsKnown && sxy.known;
    }

    // Keep non-matching inputs conservative until a PSX-authoritative GTE
    // trace covers that window.
    return out;
}

Mode25TriangleGeometryTrace TraceMode25TriangleGeometry(
    const Mode25TriangleGeometryInput& input) {
    Mode25TriangleGeometryTrace out{};
    out.sxy = input.sxy;
    out.szAfterRtpt = input.szAfterRtpt;

    out.projectedSxyKnown = true;
    std::array<uint32_t, 3> sxyWords{};
    for (std::size_t i = 0; i < input.sxy.size(); ++i) {
        const GteSxy& sxy = input.sxy[i];
        out.projectedSxyKnown = out.projectedSxyKnown && sxy.known;
        if (sxy.known) {
            sxyWords[i] = sxy.word;
        } else if (sxy.candidateKnown) {
            sxyWords[i] = sxy.candidateWord;
        } else {
            out.nclip.inputsCandidateKnown = false;
            sxyWords = {};
            break;
        }
        out.nclip.inputsCandidateKnown = true;
    }
    out.nclip.inputsAuthoritative = out.projectedSxyKnown;
    if (out.nclip.inputsCandidateKnown) {
        const int64_t x0 = static_cast<int16_t>(sxyWords[0] & 0xFFFFu);
        const int64_t y0 = static_cast<int16_t>(sxyWords[0] >> 16u);
        const int64_t x1 = static_cast<int16_t>(sxyWords[1] & 0xFFFFu);
        const int64_t y1 = static_cast<int16_t>(sxyWords[1] >> 16u);
        const int64_t x2 = static_cast<int16_t>(sxyWords[2] & 0xFFFFu);
        const int64_t y2 = static_cast<int16_t>(sxyWords[2] >> 16u);
        out.nclip.mac0Candidate =
            x0 * y1 + x1 * y2 + x2 * y0 -
            x0 * y2 - x1 * y0 - x2 * y1;
        out.nclip.candidateKnown = true;
        if (out.nclip.inputsAuthoritative) {
            out.nclip.known = true;
            out.nclip.mac0 = TruncateSigned32(out.nclip.mac0Candidate);
            out.nclip.overflowKnown = true;
            out.nclip.overflow =
                out.nclip.mac0Candidate < -0x80000000ll ||
                out.nclip.mac0Candidate > 0x7FFFFFFFll;
        }
    }

    out.avsz3.inputsAuthoritative = input.zScaleFactor3Known;
    out.avsz3.inputsCandidateKnown = input.zScaleFactor3Known;
    std::array<uint32_t, 3> depth{};
    for (std::size_t i = 0; i < depth.size(); ++i) {
        const std::size_t fifoIndex = i + 1u;
        if (input.szAfterRtpt.elementKnown[fifoIndex]) {
            depth[i] = input.szAfterRtpt.sz[fifoIndex];
        } else if (input.szAfterRtpt.elementCandidateKnown[fifoIndex]) {
            depth[i] = input.szAfterRtpt.candidateSz[fifoIndex];
            out.avsz3.inputsAuthoritative = false;
        } else {
            out.avsz3.inputsCandidateKnown = false;
            out.avsz3.inputsAuthoritative = false;
            break;
        }
    }
    if (out.avsz3.inputsCandidateKnown) {
        out.avsz3.zScaleFactor3 = input.zScaleFactor3;
        const int64_t sum = static_cast<int64_t>(depth[0]) + depth[1] +
                            depth[2];
        out.avsz3.mac0Candidate =
            sum * static_cast<int64_t>(input.zScaleFactor3);
        const int64_t rawOtz = out.avsz3.mac0Candidate >> 12;
        out.avsz3.saturationCandidate = rawOtz < 0 || rawOtz > 0xFFFF;
        out.avsz3.otzCandidate = static_cast<uint16_t>(
            ClampUnsigned16(rawOtz));
        out.avsz3.candidateKnown = true;
        const bool zsf3Representable =
            input.zScaleFactor3 >= -0x8000 &&
            input.zScaleFactor3 <= 0x7FFF;
        if (out.avsz3.inputsAuthoritative && zsf3Representable) {
            out.avsz3.known = true;
            out.avsz3.mac0 = TruncateSigned32(out.avsz3.mac0Candidate);
            out.avsz3.otz = out.avsz3.otzCandidate;
            out.avsz3.saturationKnown = true;
            out.avsz3.saturated = out.avsz3.saturationCandidate;
        }
    }

    if (out.nclip.known) {
        out.visibilityKnown = true;
        out.visible = out.nclip.mac0 > 0;
    }
    if (out.avsz3.known) {
        out.otzKnown = true;
        out.otz = out.avsz3.otz;
    }
    return out;
}

